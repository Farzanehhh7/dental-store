const StoreContext = createContext<StoreContextValue | null>(null);

export function StoreProvider({ children }: { children: React.ReactNode }) {
  return (
    <AuthProvider>
      <CatalogProvider>
        <ContentProvider>
          <CartProvider>
            <RfqProvider>
              <OrdersProvider>
                <StoreContextComposer>{children}</StoreContextComposer>
              </OrdersProvider>
            </RfqProvider>
          </CartProvider>
        </ContentProvider>
      </CatalogProvider>
    </AuthProvider>
  );
}

